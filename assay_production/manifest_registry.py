"""The MANIFEST.md answer key, as a machine-readable registry.

MANIFEST.md is written for people. Consumers such as SWIZZLE and Warden need
the same answers as data: which file, what class of specimen, what verdict a
working verifier must reach. This module is that translation.

There are four copies of each answer, and they are all checked against each
other every time `verify_manifest.py` runs:

1. the human prose in MANIFEST.md (checked by a short "prose marker" per
   specimen: a phrase that must appear in the right row or section);
2. the machine block at the end of MANIFEST.md (generated, never hand-edited);
3. the table `MANIFEST_SPECIMENS` below (the source the block is built from);
4. `registry.json`, which consumers read (generated, never hand-edited).

Any disagreement, in any direction, fails verification. Changing an answer
therefore takes a deliberate, reviewable act: edit the prose and the table,
then run the explicit write command, which refuses to run unless the
corpus still behaves as the claims say.

    python3 -m assay_production.manifest_registry          # print registry.json
    python3 -m assay_production.manifest_registry --write  # re-record everything

`--write` is the only thing that records content hashes. A specimen edit is a
change to the answer key and must be reviewed like one.

Only specimens whose files exist are registered. `cns_specimens.py` describes
a CNS-readiness catalogue whose files (`specimens/cns/`) have not been built;
those are deliberately absent so no consumer is handed a path to nothing.
"""
