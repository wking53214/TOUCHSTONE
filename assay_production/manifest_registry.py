_REQUIRED_KEYS = ("id", "cls", "path", "companions", "verdict", "failure_mode", "section", "what", "prose")


# --- table checks ----------------------------------------------------------

def table_problems(specs: Optional[List[dict]] = None) -> List[str]:
    """Plain-language problems with the table itself. Empty means it is sound."""
    specs = MANIFEST_SPECIMENS if specs is None else specs
    problems: List[str] = []
    seen: Dict[str, int] = {}
    for n, spec in enumerate(specs, 1):
        missing = [k for k in _REQUIRED_KEYS if k not in spec]
        if missing:
            problems.append(f"table row {n} ({spec.get('id', '?')}) lacks {', '.join(missing)}")
        sid = spec.get("id")
        if sid in seen:
            problems.append(f"duplicate specimen id {sid!r} (rows {seen[sid]} and {n}); "
                            "the later row would silently replace the earlier one")
        else:
            seen[sid] = n
    return problems


def check_table(specs: Optional[List[dict]] = None) -> None:
    problems = table_problems(specs)
    if problems:
        if any("duplicate" in p for p in problems):
            raise DuplicateSpecimenId("; ".join(problems))
        raise ValueError("; ".join(problems))


# --- hashing ---------------------------------------------------------------

def is_bytecode(parts: Tuple[str, ...]) -> bool:
    """True for a bytecode cache entry. They are hashed like any other file and are never expected."""
    return "__pycache__" in parts or parts[-1].endswith((".pyc", ".pyo"))


def _entries(base: Path):
    """Every entry under a directory as (relative parts, kind, path); links are never followed.

    kind is "file", "link" (a symbolic link, to a file or a folder) or "special"
    (a device, pipe or socket). Folders themselves are not listed.
    """
    import os
    for cur, dirs, files in os.walk(base, followlinks=False):
        for name in sorted(dirs):
            full = os.path.join(cur, name)
            if os.path.islink(full):
                yield Path(full).relative_to(base).parts, "link", Path(full)
        dirs[:] = sorted(d for d in dirs if not os.path.islink(os.path.join(cur, d)))
        for name in sorted(files):
            full = Path(cur) / name
            rel = full.relative_to(base).parts
            if full.is_symlink():
                yield rel, "link", full
            elif full.is_file():
                yield rel, "file", full
            else:
                yield rel, "special", full


def _entry_hash(kind: str, path: Path) -> str:
    """A file's SHA-256, or a marker no file can have for a link or special file."""
    import os
    if kind == "file":
        return hashlib.sha256(path.read_bytes()).hexdigest()
    if kind == "link":
        return "symlink->" + os.readlink(path)
    return "special-file"


def hash_path(root: Path, rel: str) -> Optional[str]:
    """SHA-256 of a file's raw bytes, or of a whole directory tree.

    Raw bytes on purpose: the flattened specimens are damaged precisely in
    their line endings and encodings, so any decoding would hide the damage.
    A directory hashes its files' relative paths and hashes in sorted order,
    bytecode caches included (a planted .pyc changes the hash). A symbolic
    link never hashes like the file it points at: it hashes as the text
    "symlink->target", so a specimen replaced by a link to identical content
    no longer matches. Missing paths give None.
    """
    target = Path(root) / rel
    if target.is_symlink():
        return _entry_hash("link", target)
    if target.is_file():
        return hashlib.sha256(target.read_bytes()).hexdigest()
    if target.is_dir():
        outer = hashlib.sha256()
        for sub, kind, path in sorted(_entries(target), key=lambda e: e[0]):
            outer.update(("/".join(sub) + "\0").encode("utf-8"))
            outer.update(_entry_hash(kind, path).encode("utf-8", "surrogateescape") + b"\n")
        return outer.hexdigest()
    return None


def corpus_files(root: Path) -> Dict[str, str]:
    """Hash of every entry under specimens/, registered or not.

    Bytecode caches, symbolic links and special files are listed too (a link
    as "symlink->target"), so each of them shows up as a change.
    """
    base = Path(root) / "specimens"
    out: Dict[str, str] = {}
    if base.is_symlink():
        out["specimens"] = _entry_hash("link", base)
    elif base.is_dir():
        for sub, kind, path in _entries(base):
            out[(Path("specimens") / Path(*sub)).as_posix()] = _entry_hash(kind, path)
    return dict(sorted(out.items()))


def corpus_layout_problems(root: Path, recorded: Optional[Dict[str, str]] = None) -> List[Tuple[str, str]]:
    """What must never be under specimens/, as (reason code, plain text).

    Symbolic links, special files and bytecode caches are always wrong. When
    the recorded list of files is given, any file that is not on it is wrong too.
    """
    base = Path(root) / "specimens"
    problems: List[Tuple[str, str]] = []
    if base.is_symlink():
        return [("symlink", "specimens/ is itself a symbolic link")]
    if not base.is_dir():
        return problems
    for sub, kind, path in _entries(base):
        name = (Path("specimens") / Path(*sub)).as_posix()
        if kind == "link":
            import os
            problems.append(("symlink", f"{name} is a symbolic link to {os.readlink(path)} (a specimen must be "
                                        "the file itself, even if the link points at identical content)"))
        elif kind == "special":
            problems.append(("unexpected_file", f"{name} is not a regular file"))
        elif is_bytecode(sub):
            problems.append(("bytecode", f"{name} is a compiled bytecode file; none belongs in the corpus and "
                                          "the verifier never imports one"))
        elif recorded is not None and name not in recorded:
            problems.append(("unexpected_file", f"{name} is not in the recorded list of specimen files"))
    return problems


def block_digest(block_text: str) -> str:
    """SHA-256 of the machine block's text, tolerant of Windows line endings."""
    return hashlib.sha256(block_text.replace("\r\n", "\n").encode("utf-8")).hexdigest()


# --- the machine block -----------------------------------------------------

def table_record(spec: dict) -> dict:
    """The part of a block record that comes from the table (no hashes)."""
    return {"id": spec["id"], "class": spec["cls"], "path": spec["path"],
            "companions": list(spec["companions"]), "verdict": spec["verdict"],
            "failure_mode": spec["failure_mode"], "section": spec["section"],
            "what": spec["what"], "prose": spec["prose"]}


def build_block(root: Path = ROOT) -> dict:
    """The machine block as it should read right now: table plus live file hashes."""
    check_table()
    records = []
    for spec in MANIFEST_SPECIMENS:
        rec = table_record(spec)
        rec["sha256"] = hash_path(root, spec["path"])
        rec["companion_sha256"] = {c: hash_path(root, c) for c in spec["companions"]}
        records.append(rec)
    return {"format": BLOCK_FORMAT, "records": records, "corpus_files": corpus_files(root)}


def block_to_text(block: dict) -> str:
    return json.dumps(block, indent=1, sort_keys=True, ensure_ascii=True)


def extract_block(manifest_text: str) -> Tuple[Optional[str], Optional[str]]:
    """(block json text, problem). Exactly one delimited block is allowed."""
    text = manifest_text.replace("\r\n", "\n")
    begins = _BLOCK_BEGIN_RE.findall(text)
    ends = text.count(BLOCK_END)
    if len(begins) != 1 or ends != 1:
        return None, (f"MANIFEST.md must contain exactly one machine block "
                      f"(found {len(begins)} begin marker(s) and {ends} end marker(s))")
    start = _BLOCK_BEGIN_RE.search(text).end()
    stop = text.index(BLOCK_END)
    if stop < start:
        return None, "MANIFEST.md machine block markers are in the wrong order"
    inner = text[start:stop]
    m = re.fullmatch(r"\s*```json\n(.*)\n```\s*", inner, re.S)
    if not m:
        return None, "the machine block in MANIFEST.md is not a single ```json fenced block"
    return m.group(1), None


def manifest_without_block(manifest_text: str) -> str:
    """The human prose only: everything outside the machine block."""
    text = manifest_text.replace("\r\n", "\n")
    m = _BLOCK_BEGIN_RE.search(text)
    if not m or BLOCK_END not in text:
        return text
    return text[:m.start()] + text[text.index(BLOCK_END) + len(BLOCK_END):]


BLOCK_SECTION_TITLE = "## Machine-readable answer key"
_BLOCK_INTRO = (
    "{title}\n\n"
    "The block below is the same answer key as the prose above, as data. It is generated by\n"
    "`python3 -m assay_production.manifest_registry --write` and checked by `verify_manifest.py`\n"
    "on every run. Do not edit it by hand: any difference from the table in\n"
    "`assay_production/manifest_registry.py`, from `assay_production/registry.json` or from the\n"
    "files on disk makes verification fail. It also records the SHA-256 of every file under\n"
    "`specimens/`, so a changed specimen is caught even if it still looks fine.\n\n"
)


def render_block_section(block_text: str) -> str:
    return (_BLOCK_INTRO.format(title=BLOCK_SECTION_TITLE) + BLOCK_BEGIN + "\n```json\n" + block_text +
            "\n```\n" + BLOCK_END + "\n")


def replace_block(manifest_text: str, block_text: str) -> str:
    """Swap the block's contents, or append the whole section if there is none yet."""
    text = manifest_text.replace("\r\n", "\n")
    if _BLOCK_BEGIN_RE.search(text) and BLOCK_END in text:
        start = _BLOCK_BEGIN_RE.search(text).start()
        stop = text.index(BLOCK_END) + len(BLOCK_END)
        return text[:start] + BLOCK_BEGIN + "\n```json\n" + block_text + "\n```\n" + BLOCK_END + text[stop:]
    return text.rstrip("\n") + "\n\n---\n\n" + render_block_section(block_text)


# --- the registry ----------------------------------------------------------

def build_manifest_registry(root: Path = ROOT, block: Optional[dict] = None,
                            statuses: Optional[Dict[str, dict]] = None) -> SpecimenRegistry:
    """Table plus hashes plus derived validation status, as a registry.

    Raises DuplicateSpecimenId rather than letting a later entry replace an
    earlier one.
    """
    check_table()
    block = block if block is not None else build_block(root)
    by_id = {r["id"]: r for r in block["records"]}
    digest = block_digest(block_to_text(block))
    registry = SpecimenRegistry(root)
    for spec in MANIFEST_SPECIMENS:
        rec = by_id[spec["id"]]
        status = (statuses or {}).get(spec["id"]) or {
            "manifest_status": "ANSWER_KEY_UNVALIDATED",
            "validation": {"level": "UNVALIDATED", "claims_asserted": [],
                           "reason": "no verification run has recorded a status for this entry"}}
        registry.register(SpecimenRecord(
            specimen_id=spec["id"], specimen_version="1.0.0",
            specimen_class=spec["cls"], source_revision="MANIFEST.md",
            path=spec["path"], expected_behavior=spec["what"],
            failure_mode=spec["failure_mode"], epistemic_status="RECORDED_IN_MANIFEST",
            provenance=f"ASSAY MANIFEST.md section {spec['section']}",
            intended_test=spec["cls"].lower(), expected_verdict=spec["verdict"],
            manifest_status=status["manifest_status"],
            tags=[spec["cls"].lower()],
            metadata={"manifest_section": spec["section"], "companions": list(spec["companions"])},
            sha256=rec["sha256"], companion_sha256=dict(rec["companion_sha256"]),
            manifest_block_sha256=digest, validation=status["validation"],
        ))
    return registry


def missing_paths(root: Path = ROOT) -> List[str]:
    """Every registered path, primary or companion, that does not exist."""
    out = []
    for spec in MANIFEST_SPECIMENS:
        for rel in [spec["path"], *spec["companions"]]:
            if not (Path(root) / rel).exists():
                out.append(f"{spec['id']}: {rel}")
    return out


def render(root: Path = ROOT, block: Optional[dict] = None, statuses: Optional[Dict[str, dict]] = None) -> str:
    reg = build_manifest_registry(root, block, statuses)
    data: Dict[str, dict] = {sid: rec.to_dict() for sid, rec in reg._records.items()}
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def registry_path(root: Path = ROOT) -> Path:
    return Path(root) / "assay_production" / "registry.json"


def load_registry_strict(path: Path) -> Tuple[Optional[dict], Optional[str]]:
    """Parse registry.json, refusing duplicate keys (JSON would silently keep the last)."""
    dupes: List[str] = []

    def pairs(items):
        seen: Dict[str, object] = {}
        for k, v in items:
            if k in seen:
                dupes.append(k)
            seen[k] = v
        return seen

    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"), object_pairs_hook=pairs)
    except (OSError, ValueError) as exc:
        return None, f"registry.json cannot be read: {exc}"
    if dupes:
        return data, "registry.json repeats the id(s): " + ", ".join(sorted(set(dupes)))
    return data, None


def main(argv: List[str]) -> int:
    if "--write" in argv:
        from .verification import write_all
        return write_all(ROOT)
    problems = table_problems()
    if problems:
        print("refusing to print a registry from an unsound table:", file=sys.stderr)
        for p in problems:
            print("  " + p, file=sys.stderr)
        return 1
    missing = missing_paths()
    if missing:
        print("refusing to publish a registry that points at missing files:", file=sys.stderr)
        for m in missing:
            print("  " + m, file=sys.stderr)
        return 1
    # Printing shows the committed statuses, not freshly derived ones: deriving
    # them means running the specimens, and that only happens in --write.
    data, _ = load_registry_strict(registry_path())
    statuses = {sid: {"manifest_status": d.get("manifest_status", "ANSWER_KEY_UNVALIDATED"),
                      "validation": d.get("validation", {})} for sid, d in (data or {}).items()}
    sys.stdout.write(render(ROOT, statuses=statuses))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
