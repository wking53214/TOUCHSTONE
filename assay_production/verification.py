#: Similarity two files must share to count as "the same content" (3.3).
#: Measured on the real pair: 1.000, because the flattened copy is identical to
#: the canonical file once whitespace is removed. Measured between every other
#: pair of Python files in the corpus: the highest is 0.951 (a faithful
#: reconstruction beside its source), then 0.847 (two files of the same lineage),
#: and most pairs are far lower. 0.99 therefore accepts a real duplicate with
#: only trivial differences and rejects related-but-different files, which a
#: looser threshold would not. tests/test_verifier.py re-measures all of this.
SAME_CONTENT_THRESHOLD = 0.99
SHINGLE = 16

