_IMPORT_RE = {"numpy": re.compile(r"^\s*(?:import|from)\s+numpy\b", re.M),
              "matplotlib": re.compile(r"^\s*(?:import|from)\s+matplotlib\b", re.M)}
_TODO_RE = re.compile(r"\b" + "TO" + "DO" + r"\b")


def count_todo_markers(root: Path) -> int:
    """Unfinished-work markers in the specimens, the manifest and the code (README and tests excluded)."""
    paths = [p for p in (Path(root) / "specimens").rglob("*") if p.is_file() and "__pycache__" not in p.parts]
    paths += [Path(root) / "MANIFEST.md", Path(root) / "verify_manifest.py"]
    paths += sorted((Path(root) / "assay_production").glob("*.py"))
    return sum(len(_TODO_RE.findall(p.read_text(encoding="utf-8", errors="replace")))
               for p in paths if p.is_file() and p.suffix in (".py", ".md", ".txt", ""))


def import_counts(root: Path) -> Dict[str, int]:
    files = [p for p in (Path(root) / "specimens").rglob("*.py") if "__pycache__" not in p.parts]
    texts = [p.read_text(encoding="utf-8", errors="replace") for p in files]
    return {name: sum(1 for t in texts if rx.search(t)) for name, rx in _IMPORT_RE.items()}


def readme_block(root: Path, statuses: Dict[str, dict]) -> str:
    levels = {EXECUTION: 0, STATIC: 0, UNVALIDATED: 0}
    for st in statuses.values():
        levels[st["validation"]["level"]] += 1
    by_class: Dict[str, int] = {}
    for s in mr.MANIFEST_SPECIMENS:
        by_class[s["cls"]] = by_class.get(s["cls"], 0) + 1
    imports = import_counts(root)
    files = len(mr.corpus_files(root))
    kinds = ", ".join(f"{k.lower().replace('_', ' ')} {v}" for k, v in sorted(by_class.items()))
    return "\n".join([
        README_BEGIN,
        "**The answer key at a glance** (generated by the verifier's write command; `verify_manifest.py` "
        "fails if any number here drifts)",
        "",
        f"- Specimens in the answer key: **{len(statuses)}** ({kinds}).",
        f"- **{levels[EXECUTION]}** are `VERIFIED_BY_EXECUTION`: the verifier ran the specimen in a sandbox and "
        "asserted the behaviour the verdict names.",
        f"- **{levels[STATIC]}** are `VERIFIED_BY_STATIC_CHECK`: the verdict is a property of the file text and "
        "the verifier compared the text. Nothing was run.",
        f"- **{levels[UNVALIDATED]}** are `UNVALIDATED`: the verdict rests on a human judgement or an outside "
        "measurement the verifier does not repeat. Each entry in `registry.json` says why.",
        f"- Files under `specimens/` whose SHA-256 is recorded and checked: **{files}**.",
        f"- Specimen files that import numpy: **{imports['numpy']}**; matplotlib: **{imports['matplotlib']}**.",
        f"- Unfinished-work markers (the word TO-DO in capitals) in the specimens, manifest and code: "
        f"**{count_todo_markers(root)}**.",
        README_END])


