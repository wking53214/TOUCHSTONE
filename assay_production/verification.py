"""The checks behind `verify_manifest.py`, and the command that re-records the key.

Two jobs, one engine:

* `main()` (verify): run every claim, print PASS/FAIL lines, and exit non-zero
  on any failure, in plain words that say which verdict is now unprovable and
  what to do next.
* `write_all()` (--write): refuse to run unless the corpus still behaves as
  the claims say, then re-record the machine block in MANIFEST.md, every
  content hash, the validation status of every entry in registry.json, and
  the generated status block in README.md. Nothing else writes those.

What "validated" means here (and what it does not)
--------------------------------------------------
Each registry entry gets one of three levels, derived from what this run
really asserted, never typed by hand:

VERIFIED_BY_EXECUTION   the verifier ran the specimen (in the sandbox) and
                        asserted the behaviour its verdict names.
VERIFIED_BY_STATIC_CHECK the verdict is itself a property of the file text and
                        the verifier compared the text. Nothing was run.
UNVALIDATED             the verifier checked only that files exist, parse, are
                        still damaged as described, and are unchanged. The
                        verdict rests on a human judgement or an outside
                        measurement that this verifier does not repeat. The
                        entry says why.
"""
