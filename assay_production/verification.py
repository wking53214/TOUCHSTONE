# --------------------------------------------------------------------- model

@dataclass
class Claim:
    id: str
    label: str
    ok: bool
    kind: str = "static"            # "static", "execution" or "meta"
    entries: Tuple[str, ...] = ()    # registry entries this claim supports
    skipped: bool = False            # could not be asserted on this machine
    regen: bool = False              # --write is allowed to fix this one
    problem: str = ""
    next_step: str = ""
    unprovable: Tuple[str, ...] = ()  # entries named in the failure message (default: entries)
    consequence: str = ""             # replaces the "verdicts that can no longer be trusted" line
    reason: str = ""                  # short machine-readable cause: timeout, stray_write, hash_mismatch, ...


@dataclass
class Report:
    claims: List[Claim] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)
    derived: Dict[str, dict] = field(default_factory=dict)
    skipped_entries: List[str] = field(default_factory=list)

    @property
    def by_id(self) -> Dict[str, Claim]:
        return {c.id: c for c in self.claims}

    @property
    def failures(self) -> List[Claim]:
        return [c for c in self.claims if not c.ok and not c.skipped]

    @property
    def skips(self) -> List[Claim]:
        return [c for c in self.claims if c.skipped]


@dataclass(frozen=True)
class Rule:
    level: str
    required: Tuple[str, ...] = ()
    gap: str = ""


