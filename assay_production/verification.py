def render_report(report: Report, root: Path, *, show_pass: bool = True) -> Tuple[str, bool]:
    verdicts = _verdicts()
    lines: List[str] = []
    for c in report.claims:
        if c.skipped:
            lines.append(f"  SKIP  {c.label}")
        elif show_pass or not c.ok:
            lines.append(f"  {'PASS' if c.ok else 'FAIL'}  {c.label}")
    failures = report.failures
    total = [c for c in report.claims if not c.skipped]
    passed = len(total) - len(failures)
    lines.append("")
    lines.append(f"{passed}/{len(total)} manifest claims hold")
    if report.skips:
        lines.append(f"{len(report.skips)} claim(s) could not be run on this machine (missing library): "
                     + ", ".join(c.id for c in report.skips)
                     + ". Their entries keep the status already recorded in registry.json. "
                       "Install numpy and matplotlib, or run with --strict, to prove them here.")
    if failures:
        lines.append("")
        lines.append("MANIFEST DRIFT -- the answer key no longer matches the corpus.")
        lines.append("A specimen that was 'fixed' is a specimen destroyed; check whether")
        lines.append("the repair was intended before updating MANIFEST.md to match.")
        lines.append("")
        lines.append("WHAT FAILED, WHAT IT MEANS, AND WHAT TO DO")
        for c in failures:
            lines.append("")
            lines.append(f"* {c.label}")
            if c.reason:
                lines.append(f"    Reason: {c.reason}")
            if c.problem:
                lines.append(f"    What happened: {c.problem}")
            names = [f"{e} (verdict {verdicts.get(e, '?')})" for e in dict.fromkeys(c.unprovable)]
            if c.consequence:
                lines.append(f"    What it means: {c.consequence}")
            elif names:
                lines.append("    Verdicts that can no longer be trusted until this is resolved: "
                             + ", ".join(names[:12]) + (f", and {len(names) - 12} more" if len(names) > 12 else ""))
            lines.append(f"    What to do: {c.next_step}")
        return "\n".join(lines), False
    return "\n".join(lines) + "\nThe corpus matches its answer key.", True


