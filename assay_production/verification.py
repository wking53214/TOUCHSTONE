_REASON_BY_PREFIX = (("hash.", "hash_mismatch"), ("specimens.layout", "unexpected_file"),
                     ("sandbox.guard", "stray_write"), ("sandbox.corpus_untouched", "stray_write"),
                     ("manifest.", "answer_key_drift"), ("registry.", "answer_key_drift"),
                     ("readme.", "answer_key_drift"), ("table.", "answer_key_drift"))


def default_reason(cid: str, kind: str) -> str:
    """A short cause for a failed claim that did not name its own (see Claim.reason)."""
    for prefix, reason in _REASON_BY_PREFIX:
        if cid.startswith(prefix):
            return reason
    if cid.startswith(("pair.", "uztc.", "fm3_", "fm_", "ref.")) and kind != "execution":
        return "specimen_changed"
    return "claim_failed"


class Verifier:
    def __init__(self, root: Path, *, strict: bool = False):
        self.root = Path(root)
        self.specimens = self.root / "specimens"
        self.strict = strict
        self.report = Report()
        self.sandbox_runs: List[Tuple[str, SandboxResult, Tuple[str, ...]]] = []
        self.deadline = time.monotonic() + sandbox_module.total_budget()

    # -- recording ----------------------------------------------------------
    def check(self, cid: str, label: str, ok: bool, *, kind: str = "static", entries: Sequence[str] = (),
              regen: bool = False, problem: str = "", next_step: str = "", unprovable: Sequence[str] = (),
              skipped: bool = False, consequence: str = "", reason: str = "") -> bool:
        self.report.claims.append(Claim(cid, label, bool(ok), kind, tuple(entries), skipped, regen, problem,
                                        next_step or NEXT_DRIFT, tuple(unprovable) or tuple(entries),
                                        consequence, "" if ok else (reason or default_reason(cid, kind))))
        return bool(ok)

    # -- sandbox ------------------------------------------------------------
    def run(self, name: str, mode: str, target: Path, entries: Sequence[str] = (), **kw) -> SandboxResult:
        res = run_in_sandbox(mode, target, deadline=self.deadline, **kw)
        self.sandbox_runs.append((name, res, tuple(entries)))
        return res

    def sandbox_problem(self, res: SandboxResult) -> str:
        return "; ".join(f"[{code}] {text}" for code, text in res.problems())

    def exec_claim(self, cid: str, label: str, entries: Sequence[str], res: SandboxResult,
                   condition: Callable[[SandboxResult], bool], *, expect_error: bool = False) -> bool:
        """Record a claim whose proof is a sandboxed run. A tripped guard always fails it."""
        if res.missing_dependency and not res.violations:
            self.check(cid, label + f" (not run: {res.missing_dependency} is not installed)", False,
                       kind="execution", entries=entries, skipped=True)
            self.report.skipped_entries.extend(e for e in entries if e not in self.report.skipped_entries)
            return False
        clean = res.clean and res.completed and not res.timed_out
        ok = clean and (expect_error or not res.error) and condition(res)
        problem = "" if ok else (self.sandbox_problem(res) or "the run did not show the behaviour the claim requires")
        reason = res.reason_code or "behaviour_changed"
        return self.check(cid, label, ok, kind="execution", entries=entries, problem=problem, reason=reason)

    # ---------------------------------------------------------------- phases
    def all(self) -> Report:
        before = mr.corpus_files(self.root)
        self.table_phase()
        self.layout_phase()
        self.pairs_phase()
        self.progression_phase()
        self.failure_modes_phase()
        self.references_phase()
        self.sandbox_phase(before)
        self.answer_key_phase()
        self.finish()
        return self.report

    # -- 0. table -----------------------------------------------------------
    def table_phase(self) -> None:
        problems = mr.table_problems()
        self.check("table.sound", "table: every specimen id is unique and every row is complete", not problems,
                   kind="meta", problem="; ".join(problems),
                   next_step="Fix assay_production/manifest_registry.py so every id appears once, then run "
                             "`python3 -m assay_production.manifest_registry --write`. Until then the registry "
                             "cannot be trusted: a repeated id silently replaces the earlier entry.",
                   unprovable=[p.split("'")[1] for p in problems if "duplicate" in p and "'" in p])

    # -- 0b. the folder itself -------------------------------------------------
    def layout_phase(self) -> None:
        problems = mr.corpus_layout_problems(self.root)
        codes = [c for c, _ in problems]
        self.check("specimens.layout",
                   "specimens/: only plain files (no symbolic links, special files or bytecode caches)",
                   not problems, kind="meta", problem="; ".join(t for _, t in problems[:10])
                   + (" ..." if len(problems) > 10 else ""),
                   reason=codes[0] if codes else "",
                   next_step="Delete the link, cache or special file, or restore the real specimen with git. "
                             "A link is refused even when it points at identical content: the verifier hashes "
                             "and runs files, and a link lets the content change without the hash noticing.",
                   unprovable=sorted({e for _, t in problems for e in entries_for_path(t.split(" ")[0])}))

    # -- 1. reconstruction pairs ---------------------------------------------
    def pairs_phase(self) -> None:
        for slug, (eid, source_rel, adapter_rel) in PAIR_SLUGS.items():
            source, adapter = self.specimens / source_rel, self.specimens / adapter_rel
            name = source.name
            self.check(f"pair.{slug}.intact", f"pair intact: {name} + {adapter.name}",
                       source.is_file() and adapter.is_file(), entries=[eid],
                       problem="one half of the pair is missing; a pair with a missing half is not a pair")
            if source.is_file():
                # Flattened: one enormous line. `wc -l` reports 0 because there
                # is no terminating newline on the single line.
                self.check(f"pair.{slug}.flattened", f"{name} still flattened (0 newline-terminated lines)",
                           source.read_bytes().count(b"\n") == 0, entries=[eid],
                           problem="the degraded source has line breaks again; it was reformatted or replaced")
            if adapter.is_file():
                self.check(f"pair.{slug}.parses", f"{adapter.name} still parses", parses(adapter), entries=[eid],
                           problem="the reconstruction no longer parses as Python")
        # The same source's second, lossier reconstruction.
        src = self.specimens / "pairs/solvar_stability_governance_source.py"
        alt = self.specimens / "pairs/solvar_stability_governance_adapter.py"
        eid = "pair_solvar_stability_consolidation"
        self.check("pair.solvar_consolidation.intact",
                   f"pair intact: {src.name} + {alt.name} (the lossier consolidation)",
                   src.is_file() and alt.is_file(), entries=[eid],
                   problem="one half of the consolidation pair is missing")
        if alt.is_file():
            self.check("pair.solvar_consolidation.parses", f"{alt.name} still parses", parses(alt), entries=[eid],
                       problem="the consolidated reconstruction no longer parses as Python")

    # -- 2. progression ------------------------------------------------------
    def progression_phase(self) -> None:
        uztc = self.specimens / "progressions/uztc"
        eid = "uztc_progression"
        self.check("uztc.v10_not_parse", "uztc v1.0 still does not parse",
                   not parses(uztc / "uztc-construct-v1.0-flattened.py"), entries=[eid],
                   problem="the flattened v1.0 now parses, so it is no longer the damaged original")
        self.check("uztc.v11_parses", "uztc v1.1 still parses", parses(uztc / "uztc-construct-v1.1-purged.py"),
                   entries=[eid], problem="v1.1 no longer parses")
        self.check("uztc.v12_parses", "uztc v1.2 still parses", parses(uztc / "uztc-construct-v1.2-validated.py"),
                   entries=[eid, "fm_3_2_overclaim"], problem="v1.2 no longer parses")
        res = self.run("uztc v1.1", "probe", uztc / "uztc-construct-v1.1-purged.py", [eid], probe="names")
        self.exec_claim("uztc.v11_imports", "uztc v1.1 imports without error", [eid], res, lambda r: True)

    # -- 3. failure modes ----------------------------------------------------
    def failure_modes_phase(self) -> None:
        uztc = self.specimens / "progressions/uztc"
        # 3.1 Silent pass: imports cleanly, defines nothing. The whole point is
        # that an importability check calls this healthy.
        silent = self.specimens / "pairs/governance_os_security_source.py"
        e31 = "fm_3_1_silent_pass"
        res = self.run("3.1 silent pass", "probe", silent, [e31], probe="names")
        self.exec_claim("fm3_1.imports", "3.1 silent pass: imports without error", [e31], res, lambda r: True)
        self.exec_claim("fm3_1.zero_names", "3.1 silent pass: defines zero names", [e31], res,
                        lambda r: r.probe.get("names") == [])

        # 3.2 Overclaim: v1.2 presents as the refined endpoint and cannot run.
        res = self.run("3.2 overclaim", "probe", uztc / "uztc-construct-v1.2-validated.py",
                       ["fm_3_2_overclaim", "uztc_progression"], probe="uztc_validate")
        self.exec_claim("fm3_2.v12_raises", "3.2 overclaim: v1.2 still raises AttributeError",
                        ["fm_3_2_overclaim", "uztc_progression"], res,
                        lambda r: r.probe.get("raised") == "AttributeError")

        # 3.3 Flattening duplicate: same content, one flattened, one not.
        e33 = "fm_3_3_flattening_duplicate"
        canonical = self.specimens / "reference/wrapper/artifact_3.py"
        flattened = self.specimens / "reference/secure/artifact_1.py"
        both = canonical.is_file() and flattened.is_file()
        self.check("fm3_3.both_present", "3.3 flattening duplicate: both halves present", both, entries=[e33],
                   problem="one of the two duplicate files is missing")
        if both:
            cb, fb = canonical.read_bytes(), flattened.read_bytes()
            self.check("fm3_3.differ", "3.3 flattening duplicate: copies still differ textually", cb != fb,
                       entries=[e33], problem="the two files are now byte-identical, so nothing is flattened")
            self.check("fm3_3.secure_flattened", "3.3 flattening duplicate: secure/ copy still the flattened one",
                       fb.count(b"\n") < cb.count(b"\n"), entries=[e33],
                       problem="the secure/ copy no longer has fewer line breaks than the canonical file")
            # Provenance: 'real duplicate' means the same code, not two merely
            # different files. Compare with whitespace removed, so flattening
            # cannot hide a match and unrelated files cannot fake one.
            ct, ft = cb.decode("utf-8", "replace"), fb.decode("utf-8", "replace")
            sim, cover = content_similarity(ct, ft), definition_coverage(ct, ft)
            ok = sim >= SAME_CONTENT_THRESHOLD and cover >= SAME_CONTENT_THRESHOLD
            self.check("fm3_3.same_content",
                       f"3.3 flattening duplicate: same content once whitespace is ignored "
                       f"(text similarity {sim:.3f}, definition names shared {cover:.3f}, "
                       f"both must be at least {SAME_CONTENT_THRESHOLD})", ok, entries=[e33],
                       problem=(f"the two files share only {sim:.0%} of their text and {cover:.0%} of the "
                                f"canonical file's class and function names. They are no longer the same code "
                                f"in two layouts, so 'same content' cannot be proven."))

        # 3.4 Unreachable branch: the adapter's own self-test searches 100,000
        # inputs for a CRITICAL verdict and asserts there is none. Its kernel
        # must sit beside it, as the adapter's header says.
        adapter = self.specimens / "pairs/sre_system_resilience_evaluator_adapter.py"
        kernel = self.specimens / "reference/resilience_stability_kernel.py"
        if adapter.is_file() and kernel.is_file():
            res = self.run("3.4 unreachable", "script", adapter, ["fm_3_4_unreachable_branch"],
                           stage=[(kernel, "resilience_stability_kernel.py")])
            self.exec_claim(
                "fm3_4.critical_unreachable",
                "3.4 unreachable branch: the adapter's 100,000-sample search still finds no CRITICAL verdict",
                ["fm_3_4_unreachable_branch"], res,
                lambda r: r.exit_code == 0 and "found_critical=False" in r.stdout
                and "ALL SRE RECONSTRUCTION CHECKS PASSED" in r.stdout)
        else:
            self.check("fm3_4.critical_unreachable", "3.4 unreachable branch: adapter and kernel present", False,
                       kind="execution", entries=["fm_3_4_unreachable_branch"],
                       problem="the SRE adapter or the shared kernel file is missing")

        # 3.5 Reskinned duplicate (static only; see _RESKIN_GAP).
        solvar = self.specimens / "pairs/solvar_stability_governance_adapter.py"
        if solvar.is_file() and adapter.is_file():
            st, at = solvar.read_text(errors="replace"), adapter.read_text(errors="replace")
            ok = ("1e-4" in st and "1e-2" in st and "1e-4" in at and "1e-2" in at
                  and "class LyapunovStabilityModule" in st and "class SystemStabilityValidator" in at
                  and "class LyapunovStabilityModule" not in at and "class SystemStabilityValidator" not in st)
            self.check("fm3_5.shared_thresholds",
                       "3.5 reskinned duplicate: both files still carry the 1e-4 / 1e-2 thresholds "
                       "under different class names", ok, entries=["fm_3_5_reskinned_duplicate"],
                       problem="the shared thresholds or the two different class names are no longer there")

    # -- 4. references -------------------------------------------------------
    def references_phase(self) -> None:
        # These must remain runnable. A corpus of only broken material cannot
        # test whether a verifier ever correctly says yes.
        sandbox = self.specimens / "reference/secure/artifact_2.py"
        self.check("ref.sandbox_present", "reference sandbox present", sandbox.is_file(),
                   entries=["reference_secure_artifact_2"], problem="the reference sandbox file is missing")
        if sandbox.is_file():
            res = self.run("reference sandbox", "probe", sandbox, ["reference_secure_artifact_2"],
                           probe="capability_denied")
            self.exec_claim("ref.sandbox.enforces", "reference sandbox still enforces capabilities",
                            ["reference_secure_artifact_2"], res,
                            lambda r: r.probe.get("raised") == "CapabilityError")
        # Each reference runs as a script, in the sandbox, and must exit 0.
        for slug, (eid, rel, marker) in REFERENCES.items():
            path = self.specimens / rel
            claim = "ref.sandbox.runs" if slug == "sandbox" else f"ref.{slug}.runs"
            if not path.is_file():
                self.check(claim, f"reference {Path(rel).name} runs", False, kind="execution", entries=[eid],
                           problem="the reference file is missing")
                continue
            res = self.run(f"reference {Path(rel).name}", "script", path, [eid])
