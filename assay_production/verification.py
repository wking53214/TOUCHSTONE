# -------------------------------------------------------------- small helpers

def before_after_equal(a: Dict[str, str], b: Dict[str, str]) -> bool:
    return a == b


def _no_duplicate_keys(items):
    seen = {}
    for k, v in items:
        if k in seen:
            raise ValueError(f"repeated key {k!r}")
        seen[k] = v
    return seen


def _short(value) -> str:
    text = json.dumps(value, sort_keys=True)
    return text if len(text) <= 60 else text[:57] + "..."


def _status(level: str, asserted: List[str], what: List[str], other: List[str], reason: str) -> dict:
    return {"manifest_status": "ANSWER_KEY_" + level,
            "validation": {"level": level, "claims_asserted": asserted, "what_was_asserted": what,
                           "other_claims_checked": other, "reason": reason}}


def _block_with_recorded_hashes(root: Path, block: Optional[dict]) -> dict:
    """Table records carrying the hashes the MANIFEST.md block recorded (live hashes if there is none)."""
    live = mr.build_block(root)
    if not isinstance(block, dict):
        return live
    recorded = {r.get("id"): r for r in block.get("records", []) if isinstance(r, dict)}
    for rec in live["records"]:
        old = recorded.get(rec["id"])
        if old:
            rec["sha256"] = old.get("sha256")
            rec["companion_sha256"] = old.get("companion_sha256", {})
    if isinstance(block.get("corpus_files"), dict):
        live["corpus_files"] = block["corpus_files"]
    return live


def _registry_diffs(actual: dict, expected: dict) -> List[str]:
    out: List[str] = []
    for sid in sorted(set(actual) | set(expected)):
        a, e = actual.get(sid), expected.get(sid)
        if a is None:
            out.append(f"{sid}: expected in registry.json but missing")
            continue
        if e is None:
            out.append(f"{sid}: in registry.json but not in the answer key")
            continue
        for key in sorted(set(a) | set(e)):
            if a.get(key) != e.get(key):
                if key in ("manifest_block_sha256",):
                    continue
                out.append(f"{sid}: {key} is {_short(a.get(key))} in registry.json but should be {_short(e.get(key))}")
    return out


