    def answer_key_phase(self) -> None:
        root = self.root
        verdicts = _verdicts()
        # (a) registered files exist
        try:
            missing = mr.missing_paths(root)
        except Exception as exc:  # noqa: BLE001
            missing = [f"cannot check ({type(exc).__name__}: {exc})"]
        self.check("registry.files_exist", "registry: every registered specimen file exists", not missing,
                   kind="meta", problem="missing: " + "; ".join(missing),
                   unprovable=[m.split(":")[0] for m in missing])

        # (b) the machine block in MANIFEST.md
        manifest_path = root / "MANIFEST.md"
        manifest_text = manifest_path.read_text(encoding="utf-8", errors="replace") if manifest_path.is_file() else ""
        block_text, block_problem = mr.extract_block(manifest_text) if manifest_text else (None, "MANIFEST.md is missing")
        block: Optional[dict] = None
        if block_text is not None:
            try:
                block = json.loads(block_text, object_pairs_hook=_no_duplicate_keys)
            except ValueError as exc:
                block_problem = f"the machine block in MANIFEST.md is not valid JSON ({exc})"
        self.check("manifest.block_present", "manifest: MANIFEST.md carries one readable machine block",
                   block is not None, kind="meta", regen=True,
                   problem=block_problem or "", next_step=NEXT_REGEN, unprovable=list(verdicts))
        table_ok = not mr.table_problems()
        if block is not None and table_ok:
            self.compare_block_to_table(block, verdicts)
            self.compare_hashes(block, verdicts)
        elif block is not None:
            self.check("manifest.block_matches_table", "manifest: machine block agrees with the table", False,
                       kind="meta", problem="the table is unsound (see the first failure), so it cannot be compared",
                       unprovable=list(verdicts))
        self.prose_checks(manifest_text)

        # (c) registry.json
        self.registry_checks(block, block_text, table_ok)
        # (d) README
        self.readme_check()

    def compare_block_to_table(self, block: dict, verdicts: Dict[str, str]) -> None:
        lines: List[str] = []
        affected: List[str] = []
        recs = block.get("records") if isinstance(block, dict) else None
        if not isinstance(recs, list):
            self.check("manifest.block_matches_table", "manifest: machine block agrees with the table", False,
                       kind="meta", regen=True, problem="the machine block has no list of records",
                       next_step=NEXT_REGEN, unprovable=list(verdicts))
            return
        seen: Dict[str, dict] = {}
        for rec in recs:
            rid = rec.get("id") if isinstance(rec, dict) else None
            if rid in seen:
                lines.append(f"MANIFEST.md block repeats the id {rid!r}")
                affected.append(rid)
            seen[rid] = rec if isinstance(rec, dict) else {}
        table = {s["id"]: mr.table_record(s) for s in mr.MANIFEST_SPECIMENS}
        for sid in table:
            if sid not in seen:
                lines.append(f"{sid} is in the table but not in the MANIFEST.md block")
                affected.append(sid)
        for sid in seen:
            if sid not in table:
                lines.append(f"{sid} is in the MANIFEST.md block but not in the table")
                affected.append(sid)
        for sid, expect in table.items():
            got = seen.get(sid)
            if got is None:
                continue
            for key, want in expect.items():
                if got.get(key) != want:
                    lines.append(f"{sid}: {key} is {_short(want)} in the table but {_short(got.get(key))} "
                                 f"in the MANIFEST.md block")
                    affected.append(sid)
        self.check("manifest.block_matches_table",
                   "manifest: machine block agrees with the table (id, class, path, companions, verdict) in both directions",
                   not lines, kind="meta", regen=True, problem="; ".join(lines[:12]) + (" ..." if len(lines) > 12 else ""),
                   next_step=("The table in assay_production/manifest_registry.py and the machine block in "
                              "MANIFEST.md must say the same thing. If you meant to change an answer, change the "
                              "prose in MANIFEST.md as well, then run "
                              "`python3 -m assay_production.manifest_registry --write` and have the change "
                              "reviewed. If you did not, undo the edit."),
                   unprovable=sorted(set(affected)))

    def compare_hashes(self, block: dict, verdicts: Dict[str, str]) -> None:
        recorded = {r.get("id"): r for r in block.get("records", []) if isinstance(r, dict)}
        bad: List[str] = []
        who: List[str] = []
        for spec in mr.MANIFEST_SPECIMENS:
            rec = recorded.get(spec["id"])
            if rec is None:
                continue
            live = mr.hash_path(self.root, spec["path"])
            if live != rec.get("sha256"):
                bad.append(f"{spec['path']} no longer matches its recorded SHA-256 (used by {spec['id']}, "
                           f"verdict {spec['verdict']})")
                who.append(spec["id"])
            for comp in spec["companions"]:
                live = mr.hash_path(self.root, comp)
                if live != (rec.get("companion_sha256") or {}).get(comp):
                    bad.append(f"{comp} no longer matches its recorded SHA-256 (companion of {spec['id']}, "
                               f"verdict {spec['verdict']})")
                    who.append(spec["id"])
        self.check("hash.registered",
                   "specimen content: every registered specimen file still matches its recorded SHA-256",
                   not bad, kind="meta", regen=True, problem="; ".join(bad[:10]) + (" ..." if len(bad) > 10 else ""),
                   next_step=NEXT_DRIFT, unprovable=sorted(set(who)))
        files = block.get("corpus_files") if isinstance(block.get("corpus_files"), dict) else {}
        live_files = mr.corpus_files(self.root)
        changed = sorted(p for p in files if p in live_files and files[p] != live_files[p])
        gone = sorted(p for p in files if p not in live_files)
        new = sorted(p for p in live_files if p not in files)
        msgs = []
        who2: List[str] = []
        for p in changed:
            hit = entries_for_path(p)
            msgs.append(f"{p} changed" + (f" (used by {', '.join(f'{e} [{verdicts[e]}]' for e in hit)})" if hit else
                                           " (not a registered specimen, but SWIZZLE still scans it)"))
            who2 += hit
        for p in gone:
            hit = entries_for_path(p)
            msgs.append(f"{p} was removed" + (f" (used by {', '.join(hit)})" if hit else ""))
            who2 += hit
        for p in new:
            msgs.append(f"{p} was added and is not in the recorded list")
        self.check("hash.corpus",
                   "specimen content: no file under specimens/ was added, removed or changed since it was recorded",
                   not msgs, kind="meta", regen=True, problem="; ".join(msgs[:10]) + (" ..." if len(msgs) > 10 else ""),
                   next_step=NEXT_DRIFT, unprovable=sorted(set(who2)))

    def prose_checks(self, manifest_text: str) -> None:
        prose = mr.manifest_without_block(manifest_text) if manifest_text else ""
        lines = prose.split("\n")
        problems: List[str] = []
        affected: List[str] = []
        sections: Dict[str, str] = {}

        def section_text(find: str) -> Optional[str]:
            hits = [i for i, ln in enumerate(lines) if ln.startswith(find)]
            if len(hits) != 1:
                return None
            start = hits[0]
            level = len(lines[start]) - len(lines[start].lstrip("#"))
            end = len(lines)
            for j in range(start + 1, len(lines)):
                ln = lines[j]
                if ln.startswith("#") and (len(ln) - len(ln.lstrip("#"))) <= level:
                    end = j
                    break
            return " ".join(" ".join(lines[start:end]).split())

        for spec in mr.MANIFEST_SPECIMENS:
            marker = spec["prose"]
            if marker["unit"] == "row":
                rows = [ln for ln in lines if ln.startswith(marker["find"])]
                hay = [" ".join(r.split()) for r in rows]
                if not rows:
                    problems.append(f"{spec['id']}: MANIFEST.md has no table row starting {marker['find']!r}")
                    affected.append(spec["id"])
                    continue
                text = " ".join(hay)
            else:
                if marker["find"] not in sections:
                    sections[marker["find"]] = section_text(marker["find"]) or ""
                text = sections[marker["find"]]
                if not text:
                    problems.append(f"{spec['id']}: MANIFEST.md has no single heading starting {marker['find']!r}")
                    affected.append(spec["id"])
                    continue
            for phrase in marker["says"]:
                if " ".join(phrase.split()) not in text:
                    problems.append(f"{spec['id']}: the MANIFEST.md prose no longer says {phrase!r}, so the "
                                    f"recorded verdict {spec['verdict']} is not what the manifest states")
                    affected.append(spec["id"])
        # Both directions for the lists humans maintain: pair rows, reference rows, failure-mode headings.
        prose_sources = {m.group(1) for ln in lines for m in [re.match(r"\| `([^`]+)` \|", ln)] if m
                         and ln.count("|") >= 6 and re.search(r"flattened|source", m.group(1))}
        table_sources = {Path(s["path"]).name for s in mr.MANIFEST_SPECIMENS if s["cls"] == "RECONSTRUCTION_PAIR"}
        for extra in sorted(prose_sources - table_sources):
            problems.append(f"MANIFEST.md lists a reconstruction pair for {extra} that the table does not have")
        sec5 = section_text("## 5.") or ""
        row_names = set()
        for ln in lines:
            if re.match(r"\| `", ln) and "`" in ln:
                first_cell = ln.split("|")[1]
                if "## 5." and any(ln.startswith(p) for p in ("| `sovereign_kernel", "| `secure/", "| `code-repo", "| `resilience_", "| `citadel_")):
                    row_names |= set(re.findall(r"`([^`]+\.py)`", first_cell))
        table_refs = {s["path"].split("/", 2)[2] if s["path"].startswith("specimens/reference/") else Path(s["path"]).name
                      for s in mr.MANIFEST_SPECIMENS if s["cls"] == "REFERENCE"}
        for extra in sorted(row_names - table_refs):
            problems.append(f"MANIFEST.md section 5 lists the reference {extra} that the table does not have")
        for gone in sorted(table_refs - row_names):
            problems.append(f"the table has the reference {gone} but MANIFEST.md section 5 does not list it")
            affected += [s["id"] for s in mr.MANIFEST_SPECIMENS if s["path"].endswith(gone)]
        headings = {m.group(1) for ln in lines for m in [re.match(r"### (3\.\d)\b", ln)] if m}
        table_sections = {s["section"] for s in mr.MANIFEST_SPECIMENS if s["cls"] == "FAILURE_MODE"}
        for extra in sorted(headings - table_sections):
            problems.append(f"MANIFEST.md has a failure mode section {extra} that the table does not have")
        for gone in sorted(table_sections - headings):
            problems.append(f"the table has failure mode {gone} but MANIFEST.md has no such section")
            affected += [s["id"] for s in mr.MANIFEST_SPECIMENS if s["section"] == gone]
        self.check("manifest.prose_matches",
                   "manifest: the human-readable MANIFEST.md prose still states every recorded verdict",
                   not problems, kind="meta", problem="; ".join(problems[:10]) + (" ..." if len(problems) > 10 else ""),
                   next_step=("MANIFEST.md prose, the table and the machine block must agree. If the prose "
                              "was edited by mistake, undo it. If the answer really changed, update the table "
                              "(and its prose marker) in assay_production/manifest_registry.py as well, run "
                              "`python3 -m assay_production.manifest_registry --write`, and have the change reviewed."),
                   unprovable=sorted(set(affected)))

    def registry_checks(self, block: Optional[dict], block_text: Optional[str], table_ok: bool) -> None:
        path = mr.registry_path(self.root)
        data0, _ = mr.load_registry_strict(path) if path.is_file() else (None, None)
        self.report.derived = self.derive_statuses(data0 if isinstance(data0, dict) else {})
        self.check("registry.published", "registry: registry.json is published", path.is_file(), kind="meta",
                   regen=True, problem="assay_production/registry.json does not exist", next_step=NEXT_REGEN,
                   unprovable=list(_verdicts()))
        if not path.is_file():
            return
        data, dup_problem = mr.load_registry_strict(path)
        table_ids = [s["id"] for s in mr.MANIFEST_SPECIMENS]
        count_msgs = []
        if data is None:
            count_msgs.append(dup_problem or "registry.json cannot be read")
        else:
            if dup_problem:
                count_msgs.append(dup_problem)
            if len(data) != len(set(table_ids)):
                count_msgs.append(f"registry.json holds {len(data)} entries but the table has "
                                  f"{len(set(table_ids))} distinct ids")
            for sid in sorted(set(table_ids) - set(data)):
                count_msgs.append(f"{sid} is in the table but not in registry.json")
            for sid in sorted(set(data) - set(table_ids)):
                count_msgs.append(f"{sid} is in registry.json but not in the table")
            if block is not None:
                nrec = len(block.get("records", []))
                if nrec != len(data):
                    count_msgs.append(f"the MANIFEST.md block has {nrec} records but registry.json has {len(data)}")
        self.check("registry.counts", "registry: ids are unique and the counts agree (table, MANIFEST.md block, registry.json)",
                   not count_msgs, kind="meta", regen=True, problem="; ".join(count_msgs[:10]), next_step=NEXT_REGEN,
                   unprovable=list(_verdicts()) if count_msgs else ())
        if not table_ok:
            self.check("registry.matches_table",
                       "registry: registry.json matches manifest_registry.py (regenerate with: "
                       "python3 -m assay_production.manifest_registry --write)", False, kind="meta",
                       problem="the table is unsound, so no expected registry can be built", unprovable=list(_verdicts()))
            return

        derived = self.report.derived
        # What registry.json should say: table + the hashes recorded in the block + derived statuses.
        recorded_block = _block_with_recorded_hashes(self.root, block)
        try:
            expected_text = mr.render(self.root, recorded_block, derived)
            expected_data = json.loads(expected_text)
        except Exception as exc:  # noqa: BLE001
            self.check("registry.matches_table", "registry: registry.json matches manifest_registry.py",
                       False, kind="meta", problem=f"the expected registry could not be built ({type(exc).__name__}: {exc})")
            return
        actual_text = path.read_text(encoding="utf-8")
        diffs = _registry_diffs(data or {}, expected_data)
        digest_ok = True
        if block_text is not None and data:
            digest = mr.block_digest(block_text)
            digest_ok = all(d.get("manifest_block_sha256") == digest for d in data.values())
            if not digest_ok:
                diffs.append("manifest_block_sha256 in registry.json is not the SHA-256 of the machine block now in MANIFEST.md")
        # Statuses get their own claim so the message can say what was (not) asserted.
        status_diffs = [d for d in diffs if "validation" in d or "manifest_status" in d]
        other_diffs = [d for d in diffs if d not in status_diffs]
        self.check("registry.statuses", "registry: each entry's validation status is what this run really asserted",
                   not status_diffs, kind="meta", regen=True,
                   problem="; ".join(status_diffs[:8]) + (" ..." if len(status_diffs) > 8 else ""),
                   next_step="Statuses are derived from what the verifier actually asserted, never typed. "
                             "If a specimen stopped passing a claim, fix that first. Otherwise run "
                             "`python3 -m assay_production.manifest_registry --write` to re-record them.",
                   consequence="The validation level recorded for these entries is wrong. The specimens and their "
                               "verdicts may be fine, but the registry would tell SWIZZLE and Warden the "
                               "wrong thing about how much of the key was proven.")
        self.check("registry.matches_table",
                   "registry: registry.json matches manifest_registry.py (regenerate with: "
                   "python3 -m assay_production.manifest_registry --write)",
                   actual_text == expected_text, kind="meta", regen=True,
                   problem=("; ".join(other_diffs[:10]) if other_diffs else
                            "registry.json differs from the registry generated from the table, the MANIFEST.md "
                            "block and this run (formatting, field order or an extra field)"),
                   next_step=("registry.json is generated, never hand-edited. If you changed an answer on purpose, "
                              "run `python3 -m assay_production.manifest_registry --write` and have the result "
                              "reviewed. If you did not, restore the file with git."),
                   consequence="SWIZZLE and Warden read registry.json. If it is not the key MANIFEST.md states, "
                               "every score computed from it is a score against a different answer key: the "
                               "verdicts of the entries named above cannot be trusted until it is regenerated.")

    def derive_statuses(self, previous: dict) -> Dict[str, dict]:
        claims = self.report.by_id
        out: Dict[str, dict] = {}
        for spec in mr.MANIFEST_SPECIMENS:
            sid = spec["id"]
            rule = RULES.get(sid)
            if rule is None:
                rule = Rule(UNVALIDATED, gap="no executable claim is defined for this entry")
            related_ok = sorted(c.id for c in self.report.claims if sid in c.entries and c.ok and not c.skipped)
            if rule.level == UNVALIDATED:
                out[sid] = _status(UNVALIDATED, [], [], related_ok, rule.gap)
                continue
            req = [claims.get(cid) for cid in rule.required]
            if any(c is None for c in req):
                out[sid] = _status(UNVALIDATED, [], [], related_ok, "a claim this status depends on is not defined")
            elif any(c.skipped for c in req if c):
                old = previous.get(sid) if isinstance(previous, dict) else None
                if old and old.get("validation"):
                    out[sid] = {"manifest_status": old.get("manifest_status", "ANSWER_KEY_UNVALIDATED"),
                                "validation": old["validation"]}
                    if sid not in self.report.skipped_entries:
                        self.report.skipped_entries.append(sid)
                else:
                    out[sid] = _status(UNVALIDATED, [], [], related_ok,
                                       "its claims could not be run on this machine (a required library is missing)")
            elif all(c.ok for c in req if c):
                out[sid] = _status(rule.level, list(rule.required), [c.label for c in req if c],
                                   [i for i in related_ok if i not in rule.required], "")
            else:
                failed = [c.id for c in req if c and not c.ok]
                out[sid] = _status(UNVALIDATED, [], [], related_ok, "claim(s) failing: " + ", ".join(failed))
        return out

    def readme_check(self) -> None:
        readme = self.root / "README.md"
        text = readme.read_text(encoding="utf-8") if readme.is_file() else ""
        m = _README_BEGIN_RE.search(text)
        statuses = self.report.derived
        if not statuses:
            self.check("readme.status_block", "readme: the generated status block matches the answer key", False,
                       kind="meta", regen=True, problem="statuses could not be derived (see earlier failures)",
                       next_step=NEXT_REGEN)
            return
        expected = readme_block(self.root, statuses)
        if not m or README_END not in text:
            self.check("readme.status_block", "readme: the generated status block matches the answer key", False,
                       kind="meta", regen=True,
                       problem="README.md has no status block between its ASSAY-STATUS markers",
                       next_step=NEXT_REGEN)
            return
        current = text[m.start(): text.index(README_END) + len(README_END)]
        self.check("readme.status_block", "readme: the generated status block matches the answer key",
                   current == expected, kind="meta", regen=True,
                   consequence="The README tells readers how much of the key is proven. Those numbers no longer "
                                "match what the verifier found, so the README would overclaim or underclaim.",
                   problem="the counts printed in README.md are not the counts this run derived",
                   next_step="README.md's status block is generated so its numbers cannot drift. Run "
                             "`python3 -m assay_production.manifest_registry --write`.")

